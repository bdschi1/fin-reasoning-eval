"""Tests for generators.plugin_scenarios — free-text Problem generation."""

from __future__ import annotations

from pathlib import Path

import pytest

from generators.plugin_reader import load_skill_from_file
from generators.plugin_scenarios import (
    PluginScenarioConfig,
    PluginScenarioGenerator,
    SKILL_CATEGORY_MAP,
)
from problems import AnswerType, Difficulty, Problem, ProblemCategory


FIXTURE_PATH = Path(__file__).parent / "fixtures" / "plugin_skill_sample.md"


def _make_spec():
    return load_skill_from_file(
        FIXTURE_PATH, slug="dcf-model", plugin="financial-analysis"
    )


def test_generate_from_spec_produces_free_text_problem():
    spec = _make_spec()
    gen = PluginScenarioGenerator(PluginScenarioConfig(seed=123))
    problem = gen.generate_from_spec(spec)

    assert isinstance(problem, Problem)
    assert problem.answer_type == AnswerType.FREE_TEXT
    assert problem.category == ProblemCategory.DCF_SANITY
    assert problem.difficulty == Difficulty.HARD


def test_generated_problem_tags_and_source():
    spec = _make_spec()
    gen = PluginScenarioGenerator(PluginScenarioConfig(seed=1))
    problem = gen.generate_from_spec(spec)

    assert "plugin-derived" in problem.tags
    assert "skill:dcf-model" in problem.tags
    assert "plugin:financial-analysis" in problem.tags
    assert problem.source == "plugin:financial-analysis/dcf-model"


def test_generated_problem_has_context_and_id():
    spec = _make_spec()
    gen = PluginScenarioGenerator(PluginScenarioConfig(seed=1))
    problem = gen.generate_from_spec(spec)

    assert problem.id  # autogenerated
    assert problem.context.company_name
    assert problem.context.ticker
    assert problem.context.revenue


def test_generated_problem_reasoning_from_output_schema():
    spec = _make_spec()
    gen = PluginScenarioGenerator(PluginScenarioConfig(seed=1))
    problem = gen.generate_from_spec(spec)

    assert problem.reasoning_steps, "reasoning_steps should not be empty"
    joined = " ".join(problem.reasoning_steps).lower()
    assert any(term in joined for term in ("dcf", "wacc", "sensitivity", "projection"))


def test_generate_from_spec_unknown_slug_falls_back_to_valuation():
    spec = load_skill_from_file(
        FIXTURE_PATH, slug="unknown-skill", plugin="fixture"
    )
    gen = PluginScenarioGenerator(PluginScenarioConfig(seed=1))
    problem = gen.generate_from_spec(spec)
    assert problem.category == ProblemCategory.VALUATION


def test_generate_one_raises():
    gen = PluginScenarioGenerator()
    with pytest.raises(NotImplementedError):
        gen.generate_one(Difficulty.HARD)


def test_skill_category_map_covers_all_pilot_skills():
    pilot = {"dcf-model", "comps-analysis", "lbo-model", "ic-memo", "earnings-preview"}
    assert pilot.issubset(SKILL_CATEGORY_MAP.keys())
